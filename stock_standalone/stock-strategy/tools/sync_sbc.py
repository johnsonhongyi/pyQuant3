"""Sync development-only SBC parity references; server calculations remain Go."""
import argparse
import ast
import hashlib
import json
from pathlib import Path


def sync(root, target):
    specs = {
        "JSONData/tdx_channel_factory.py": None,
        "JSONData/tdx_data_Day.py": {
            "td_sequential_fast", "_barslast_vec", "_cross_vec", "calc_trend_channel"},
        "ats/channel_bottom_reversal_strategy.py": "functions",
    }
    parts = ["# Generated by tools/sync_sbc.py; edit the ATS source, then sync.\n"
             "import math\nimport time\nimport numpy as np\nimport pandas as pd\n"
             "from dataclasses import dataclass\nfrom typing import *\n"]
    hashes = {}
    for relative, names in specs.items():
        raw = (root / relative).read_bytes()
        hashes[relative] = hashlib.sha256(raw).hexdigest()
        tree = ast.parse(raw.decode("utf-8-sig"))
        for node in tree.body:
            if names is None:
                include = isinstance(node, (ast.ClassDef, ast.FunctionDef))
            elif names == "functions":
                include = isinstance(node, ast.FunctionDef)
            else:
                include = isinstance(node, ast.FunctionDef) and node.name in names
            if not include:
                continue
            # The factory is in this standalone module. Keep its algorithm intact.
            for child in ast.walk(node):
                for field, value in ast.iter_fields(child):
                    if isinstance(value, list):
                        setattr(child, field, [item for item in value if not (
                            isinstance(item, ast.ImportFrom)
                            and item.module == "JSONData.tdx_channel_factory")])
            parts.append(ast.unparse(node))
    target.mkdir(parents=True, exist_ok=True)
    (target / "engine.py").write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    (target / "manifest.json").write_text(json.dumps({
        "schema_version": 1, "sources": hashes,
    }, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    base = Path(__file__).resolve().parents[1]
    parser.add_argument("--ats-root", type=Path, default=base.parent)
    args = parser.parse_args()
    reference = base / "tools/sbc_reference"
    sync(args.ats_root, reference)
    # Provenance only: native Go changes require parity-test validation.
    (base / "source/easy-stock-analysis/backend/internal/sbc/manifest.json").write_bytes(
        (reference / "manifest.json").read_bytes())
